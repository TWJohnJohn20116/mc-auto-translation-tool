package org.universaltranslator.core;

/** Cheap offline checks used to avoid unnecessary network requests. */
public final class LanguageHeuristics {
    /**
     * Every name the mod uses for itself: the three locales shipped in
     * {@code assets/universal_translator/lang/} plus the project's former name.
     *
     * <p>The mod's own chat and status messages are built from
     * {@code message.universal_translator.*} and always contain this name, so the name is the
     * part that identifies them. Matching the name instead of the bracketed form matters
     * because only some locales wrap it: {@code "MC 自动翻译工具：切换失败"} and
     * {@code "MC 自動翻譯工具：切換失敗"} carry no brackets at all, and the Traditional Chinese
     * name is a different string from the Simplified one that the old literal list hard-coded.
     * The separator and the optional {@code §}-formatting around the name are ignored, so the
     * check does not depend on the active language file.
     */
    private static final String[] SELF_NAMES = {
            "MC Auto Translation Tool",
            "MC 自动翻译工具",
            "MC 自動翻譯工具",
            "Universal Translator"
    };

    private LanguageHeuristics() {
    }

    public static boolean shouldTranslate(String text, String targetLanguage) {
        return shouldTranslateToTarget(text, isChineseTarget(targetLanguage),
                isTraditionalTarget(targetLanguage));
    }

    /**
     * What {@link #shouldTranslateToTarget(String, boolean)} assumes about the target script.
     *
     * <p>Naming the assumption is what keeps it visible: the overload exists for callers that only
     * carry the Chinese/not-Chinese boolean, and it therefore answers "Simplified". A caller that
     * holds the language identifier has to use the three-argument overload instead, otherwise a
     * {@code zh-TW} target never converts anything.
     */
    private static final boolean ASSUMED_TRADITIONAL_TARGET = false;

    /**
     * The same check with the target-language test already resolved.
     *
     * <p>The render path calls this for every visible string on every frame, so it must not
     * re-normalize the language identifier per call; the identifier is fixed for the lifetime of a
     * session, which makes the boolean a per-session constant.
     *
     * <p>Compatibility overload: it assumes the target is Simplified Chinese
     * ({@link #ASSUMED_TRADITIONAL_TARGET}). Any caller that holds the language identifier must use
     * the three-argument overload, or a Traditional target silently skips every Han-only line.
     *
     * @param chineseTarget whether {@code targetLanguage} names a Chinese variant
     */
    public static boolean shouldTranslateToTarget(String text, boolean chineseTarget) {
        return shouldTranslateToTarget(text, chineseTarget, ASSUMED_TRADITIONAL_TARGET);
    }

    /**
     * The same check with both resolved properties of the target language.
     *
     * <p>A Chinese target only gets to skip Han text when the target asks for the same script the
     * text is already written in. Simplified and Traditional are two different presets and a
     * {@code zh-TW} target has to convert Simplified input, which is the only reason that preset
     * exists at all; treating "every letter is Han" as "already translated" made the conversion
     * never happen.
     *
     * @param chineseTarget whether {@code targetLanguage} names a Chinese variant
     * @param traditionalTarget whether the target asks for Traditional Chinese characters
     */
    public static boolean shouldTranslateToTarget(
            String text,
            boolean chineseTarget,
            boolean traditionalTarget
    ) {
        if (text == null || text.trim().isEmpty()) {
            return false;
        }
        // Count letters first. Every rejected instruction fragment, marker and placeholder
        // token contains at least one letter, and lower casing never turns a non-letter into a
        // letter, so text without any letter cannot contain an internal artifact. Text such as
        // "123 / 456" therefore skips the lower casing and the fragment scans entirely.
        int letters = 0;
        int han = 0;
        // Code points, not chars: a character outside the BMP is two surrogates, and
        // Character.isLetter(char) answers false for each half. Scan by char and a name written in
        // CJK Extension B reports zero letters, so it is never translated and never protected.
        for (int index = 0; index < text.length(); ) {
            int codePoint = text.codePointAt(index);
            index += Character.charCount(codePoint);
            if (Character.isLetter(codePoint)) {
                letters++;
                if (isHanIdeograph(codePoint)) {
                    han++;
                }
            }
        }
        if (letters == 0) {
            return false;
        }
        // Messages generated by the mod itself are already localized and must remain stable.
        if (containsSelfName(text)) {
            return false;
        }
        if (TranslationOutputValidator.containsInternalArtifact(text)) {
            return false;
        }
        // Mixed Chinese/Latin labels still need their Latin portion translated. Existing Han
        // runs are protected later, so skip only when every detected letter is already Han and the
        // target does not have to convert it to the other script.
        if (chineseTarget && !traditionalTarget && han == letters) {
            return false;
        }
        return true;
    }

    /**
     * True when the text is one of the mod's own messages. Locale independent in the sense that
     * it never depends on the brackets or the separator a language file chose, only on the mod's
     * display name being present. Kept allocation free because it runs on the render thread.
     *
     * <p>The name has to open the line and be followed by the separator every such message carries.
     * A bare substring test also swallowed every server line that merely mentioned the name — an
     * announcement, another plugin's chat line, a player quoting the tool — and those were then
     * never translated, with nothing in the log to explain it.
     */
    private static boolean containsSelfName(String text) {
        int start = 0;
        while (start < text.length()) {
            char character = text.charAt(start);
            if (character == '\u00a7' && start + 1 < text.length()) {
                start += 2;
                continue;
            }
            if (character == '[' || character == '\u3010') {
                start++;
                continue;
            }
            break;
        }
        for (String selfName : SELF_NAMES) {
            if (startsWithSelfMessage(text, start, selfName)) {
                return true;
            }
        }
        return false;
    }

    private static boolean startsWithSelfMessage(String text, int start, String selfName) {
        if (!text.regionMatches(start, selfName, 0, selfName.length())) {
            return false;
        }
        int next = start + selfName.length();
        if (next >= text.length()) {
            return false;
        }
        char separator = text.charAt(next);
        return separator == ':' || separator == '\uff1a'
                || separator == ']' || separator == '\u3011';
    }

    /**
     * Exact code point ranges that count as existing Han text.
     *
     * <p>Five ranges, in code points rather than chars: the three BMP blocks the old version listed
     * (CJK_UNIFIED_IDEOGRAPHS 4E00..9FFF, CJK_UNIFIED_IDEOGRAPHS_EXTENSION_A 3400..4DBF and
     * CJK_COMPATIBILITY_IDEOGRAPHS F900..FAFF) plus CJK_UNIFIED_IDEOGRAPHS_EXTENSION_B
     * (20000..2A6DF, inside the supplementary ideographic plane) and EXTENSION C..F, which live in
     * plane 3. A char cannot express any of those, so a mixed label used to report
     * {@code han < letters} and have its rare characters sent to the provider.
     */
    private static boolean isHanIdeograph(int codePoint) {
        return (codePoint >= 0x3400 && codePoint <= 0x4dbf)
                || (codePoint >= 0x4e00 && codePoint <= 0x9fff)
                || (codePoint >= 0xf900 && codePoint <= 0xfaff)
                || (codePoint >= 0x20000 && codePoint <= 0x2fa1f)
                || (codePoint >= 0x30000 && codePoint <= 0x323af);
    }

    /**
     * Whether {@code language} asks for Traditional Chinese characters.
     *
     * <p>Settle this once per session or request, next to {@link #isChineseTarget(String)}:
     * {@link TargetLanguage#isTraditionalChinese(String)} canonicalizes its argument on every call,
     * which is too much for the render path.
     */
    static boolean isTraditionalTarget(String language) {
        return language != null && TargetLanguage.isTraditionalChinese(language);
    }

    /** True when {@code language} is {@code zh} or a {@code zh-*} variant. */
    public static boolean isChineseTarget(String language) {
        if (language == null) {
            return false;
        }
        String normalized = language.toLowerCase().replace('_', '-');
        return normalized.equals("zh") || normalized.startsWith("zh-");
    }
}
